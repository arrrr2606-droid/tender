_COMPILED = {code: re.compile(pat) for code, (_, pat) in REGIONS.items()}


def _norm(text: str) -> str:
    return text.lower().replace("ё", "е")


def name(code: str) -> str:
    return REGIONS.get(code, ("регион не определён", ""))[0]


def detect_in_text(*texts: str) -> str:
    """Код региона по тексту (адрес, название заказчика). Берётся самое раннее упоминание."""
    for text in texts:
        if not text:
            continue
        t = _norm(text)
        best = None
        for code, rx in _COMPILED.items():
            m = rx.search(t)
            if m and (best is None or m.start() < best[0]):
                best = (m.start(), code)
        if best:
            return best[1]
    return ""


def from_inn(inn: str) -> str:
    """Первые две цифры ИНН — код налоговой, почти всегда совпадает с кодом субъекта."""
    inn = (inn or "").strip()
    if len(inn) in (10, 12) and inn.isdigit():
        code = inn[:2]
        if code in REGIONS:
            return code
    return ""


def resolve(user_input: str) -> list:
    """Превращает ввод пользователя («Татарстан», «МО», «16», «УФО») в список кодов."""
    s = _norm(user_input).strip().strip(".")
    if not s:
        return []
    if s in DISTRICTS:
        return list(DISTRICTS[s])
    if s in ALIASES:
        return [ALIASES[s]]
    if s.isdigit() and s.zfill(2) in REGIONS:
        return [s.zfill(2)]
    for code, (title, _) in REGIONS.items():
        if _norm(title) == s:
            return [code]
    code = detect_in_text(s)
    if code:
        return [code]
    # «Свердловская» без слова «область» и т.п.
    hits = [c for c, (title, _) in REGIONS.items() if _norm(title).startswith(s)]
    return hits[:1]


def resolve_many(items: Iterable[str]) -> tuple:
    """-> (коды, нераспознанные строки)"""
    codes, bad = [], []
    for item in items:
        got = resolve(item)
        if got:
            codes.extend(c for c in got if c not in codes)
        else:
            bad.append(item)
    return codes, bad


def fmt(codes: Optional[list]) -> str:
    if not codes:
        return "вся Россия"
    return ", ".join(name(c) for c in codes)
